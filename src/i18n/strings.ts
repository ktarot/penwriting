export const STRINGS: Record<LanguageCode, Strings> = { ko, en, ja, vi };

/** "{name}" 자리표시자를 채운다 */
export function fill(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}
